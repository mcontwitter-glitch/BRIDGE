// Bakes collections/*.json (+ *.manifest.json, *.plan.json if present) into src/collections.gen.js (no fs in Workers).
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.env.ORDINALS_COLLECTIONS_DIR || path.join(here, '..', '..', 'collections');
const out = { collections: {}, manifests: {}, plans: {}, traits: {} };
for (const f of fs.readdirSync(dir)) {
  const j = () => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  if (/\.manifest\.json$/.test(f)) out.manifests[f.replace('.manifest.json', '')] = j();
  else if (/\.traits\.json$/.test(f)) out.traits[f.replace('.traits.json', '')] = j().tokens || {};
  else if (/\.plan\.json$/.test(f)) out.plans[f.replace('.plan.json', '')] = j();
  else if (/^[a-z0-9-]+\.json$/.test(f)) { const c = j(); out.collections[c.collection.toLowerCase()] = c; }
}
fs.writeFileSync(path.join(here, '..', 'src', 'collections.gen.js'), `// generated by build/gen-collections.js — do not edit\nexport default ${JSON.stringify(out)};\n`);
console.log(`collections: ${Object.keys(out.collections).length}, manifests: ${Object.keys(out.manifests).join(',') || 'none (recursive deliveries → 503 until setup is inscribed)'}`);
